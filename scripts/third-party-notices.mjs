// Generates THIRD_PARTY_NOTICES.md from the production dependency tree (everything bundled into the VSIX).
import { execSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const tree = JSON.parse(execSync('npm ls --omit=dev --all --long --json', { encoding: 'utf8' }));
// Optional modules pdfjs-dist loads at run time only if they are installed. They are never bundled (esbuild follows
// static imports only, and the VSIX ships no node_modules), and the canvas brings a native package per platform,
// which would make this file differ between machines. Their own dependencies are skipped with them.
const NOT_BUNDLED = new Set(['@napi-rs/canvas', 'node-readable-to-web-readable-stream']);
const seen = new Map();
(function walk(deps = {}) {
  for (const [name, info] of Object.entries(deps)) {
    if (!info.version || NOT_BUNDLED.has(name)) continue;
    // Different bundled versions need their own notices and their actual nested package/license files.
    const key = `${name}@${info.version}`;
    if (!seen.has(key)) seen.set(key, { name, version: info.version, dir: info.path });
    walk(info.dependencies);
  }
})(tree.dependencies);

const sections = [];
const summary = [];
for (const { name, version, dir } of [...seen.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
)) {
  if (!dir) throw new Error(`npm did not return the installed location of ${name}@${version}.`);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN');
  const files = readdirSync(dir).filter((f) =>
    /^(licen[sc]e|copying|notice)([._-]|$)|^third[._-]?party[._-]?(notices|licenses)/i.test(f),
  );
  const legalFiles = [];
  function collect(file) {
    if (statSync(join(dir, file)).isDirectory()) {
      for (const child of readdirSync(join(dir, file)).sort()) collect(join(file, child));
    } else legalFiles.push(file);
  }
  for (const file of files.sort()) collect(file);
  const text = legalFiles.length
    ? legalFiles
        .map((file) => {
          const raw = readFileSync(join(dir, file), 'utf8');
          // Normalize presentation whitespace; original dependency files are never modified.
          return `File: ${file}\n\n${raw
            .replace(/\r\n/g, '\n')
            .replace(/[ \t]+$/gm, '')
            .trim()}`;
        })
        .join('\n\n')
    : '(license text not included in package)';
  summary.push(`| ${name} | ${version} | ${license} |`);
  sections.push(`## ${name} ${version} — ${license}\n\n\`\`\`\n${text}\n\`\`\``);
}

writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `# Third-Party Notices\n\nSOVRAN bundles the following open-source packages. Generated by \`scripts/third-party-notices.mjs\`; do not edit by hand.\n\n| Package | Version | License |\n|---|---|---|\n${summary.join('\n')}\n\n${sections.join('\n\n')}\n`,
);
console.log(`Wrote notices for ${seen.size} packages.`);
