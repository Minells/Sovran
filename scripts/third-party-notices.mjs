// Generates THIRD_PARTY_NOTICES.md from the production dependency tree (everything bundled into the VSIX).
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { encoding: 'utf8' }));
const seen = new Map();
(function walk(deps = {}) {
  for (const [name, info] of Object.entries(deps)) {
    if (!info.version || seen.has(name)) continue;
    seen.set(name, info.version);
    walk(info.dependencies);
  }
})(tree.dependencies);

const sections = [];
const summary = [];
for (const [name, version] of [...seen.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const dir = join('node_modules', name);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'UNKNOWN';
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  const text = file && existsSync(join(dir, file)) ? readFileSync(join(dir, file), 'utf8').trim() : '(license text not included in package)';
  summary.push(`| ${name} | ${version} | ${license} |`);
  sections.push(`## ${name} ${version} — ${license}\n\n\`\`\`\n${text}\n\`\`\``);
}

writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `# Third-Party Notices\n\nSOVRAN bundles the following open-source packages. Generated by \`scripts/third-party-notices.mjs\`; do not edit by hand.\n\n| Package | Version | License |\n|---|---|---|\n${summary.join('\n')}\n\n${sections.join('\n\n')}\n`,
);
console.log(`Wrote notices for ${seen.size} packages.`);
